def init():
    conn = sqlite3.connect(DB_PATH)
    conn.execute("DROP TABLE IF EXISTS books")
    conn.execute("""
        CREATE TABLE books (
            id        INTEGER PRIMARY KEY AUTOINCREMENT,
            isbn      TEXT NOT NULL UNIQUE,
            title     TEXT NOT NULL,
            author    TEXT NOT NULL,
            genre     TEXT NOT NULL,
            year      INTEGER,
            available INTEGER NOT NULL DEFAULT 1
        )
    """)
    conn.executemany(
        "INSERT INTO books (isbn, title, author, genre, year, available) VALUES (?,?,?,?,?,?)",
        [(isbn, title, author, genre, year, int(avail)) for isbn, title, author, genre, year, avail in BOOKS],
    )
    conn.commit()
    conn.close()
    print(f"{len(BOOKS)} 件の書籍データを登録しました。")


if __name__ == "__main__":
    init()
