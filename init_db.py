def init():
    conn = sqlite3.connect(DB_PATH)

    # 書籍テーブル
    conn.execute("DROP TABLE IF EXISTS occupation_books")
    conn.execute("DROP TABLE IF EXISTS occupations")
    conn.execute("DROP TABLE IF EXISTS books")

    conn.execute("""
        CREATE TABLE books (
            id        INTEGER PRIMARY KEY AUTOINCREMENT,
            isbn      TEXT NOT NULL UNIQUE,
            title     TEXT NOT NULL,
            author    TEXT NOT NULL,
            genre     TEXT NOT NULL,
            year      INTEGER,
            available INTEGER NOT NULL DEFAULT 1
        )
    """)
    conn.executemany(
        "INSERT INTO books (isbn, title, author, genre, year, available) VALUES (?,?,?,?,?,?)",
        [(isbn, title, author, genre, year, int(avail)) for isbn, title, author, genre, year, avail in BOOKS],
    )

    # 職業テーブル
    conn.execute("""
        CREATE TABLE occupations (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            name        TEXT NOT NULL UNIQUE,
            description TEXT,
            icon        TEXT
        )
    """)
    conn.executemany(
        "INSERT INTO occupations (name, description, icon) VALUES (?,?,?)",
        OCCUPATIONS,
    )

    # 職業×書籍 紐づけテーブル
    conn.execute("""
        CREATE TABLE occupation_books (
            id             INTEGER PRIMARY KEY AUTOINCREMENT,
            occupation_id  INTEGER NOT NULL REFERENCES occupations(id),
            isbn           TEXT NOT NULL,
            note           TEXT,
            UNIQUE(occupation_id, isbn)
        )
    """)
    conn.executemany(
        """INSERT INTO occupation_books (occupation_id, isbn, note)
           SELECT o.id, ?, ?
           FROM occupations o WHERE o.name = ?""",
        [(isbn, note, occ_name) for occ_name, isbn, note in OCCUPATION_BOOKS],
    )

    conn.commit()
    conn.close()
    print(f"{len(BOOKS)} 件の書籍、{len(OCCUPATIONS)} 件の職業、{len(OCCUPATION_BOOKS)} 件の紐づけを登録しました。")


if __name__ == "__main__":
    init()
